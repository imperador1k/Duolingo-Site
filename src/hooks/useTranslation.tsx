export type Language = keyof typeof translations;
type TranslationKey = keyof typeof translations['pt'];

interface LanguageContextType {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: TranslationKey) => string;
  languages: Language[];
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>('pt');

  // Load language from localStorage on mount
  useEffect(() => {
    const savedLang = localStorage.getItem('myduolingo-lang') as Language;
    if (savedLang && translations[savedLang]) {
      setLangState(savedLang);
    }
  }, []);

  const setLang = useCallback((newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem('myduolingo-lang', newLang);
  }, []);

  const t = useCallback((key: TranslationKey) => {
    const translation = translations[lang] || translations['pt'];
    return (translation as any)[key] || (translations['pt'] as any)[key] || key;
  }, [lang]);

  const value = React.useMemo(() => ({
    lang,
    setLang,
    t,
    languages: Object.keys(translations) as Language[]
  }), [lang, setLang, t]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useTranslation must be used within a LanguageProvider');
  }
  return context;
}
